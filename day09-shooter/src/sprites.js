// ---- 굽기 ----

const hex = (s) => [parseInt(s.slice(1, 3), 16), parseInt(s.slice(3, 5), 16), parseInt(s.slice(5, 7), 16)];

// 왼쪽 절반을 가운데 열 기준으로 되접어 한 줄을 완성한다.
export function mirrorRow(half) {
  let out = half;
  for (let i = half.length - 2; i >= 0; i -= 1) out += half[i];
  return out;
}

/** 픽셀맵을 캔버스로 구워 돌려준다. faceDown이면 위아래를 뒤집는다. */
export function bakeSprite(name) {
  const map = MAPS[name];
  const pal = PALETTES[name] || PALETTES.player;
  const rows = map.rows.map(mirrorRow);
  const w = map.w;
  const h = rows.length;
  for (const [i, r] of rows.entries()) {
    if (r.length !== w) throw new Error(`sprite ${name} row ${i}: ${r.length} != ${w}`);
  }

  const cv = document.createElement('canvas');
  cv.width = w; cv.height = h;
  const ctx = cv.getContext('2d');
  const img = ctx.createImageData(w, h);
  for (let y = 0; y < h; y += 1) {
    const row = rows[map.faceDown ? h - 1 - y : y];
    for (let x = 0; x < w; x += 1) {
      const ch = row[x];
      if (ch === '.') continue;
      const slot = SLOT[ch];
      if (!slot) continue;
      const col = Array.isArray(slot) ? pal[slot[0]][slot[1]] : pal[slot];
      const [r, g, b] = hex(col);
      const o = (y * w + x) * 4;
      img.data[o] = r; img.data[o + 1] = g; img.data[o + 2] = b;
      img.data[o + 3] = ch === 'p' ? 105 : 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  return cv;
}

